const sharp = require('sharp');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const imagePath = path.join(__dirname, '../public/icon.jpg');
  const imageMetadata = await sharp(imagePath).metadata();
  if (imageMetadata.format !== 'jpeg' || !imageMetadata.width || !imageMetadata.height) {
    throw new Error('The realistic Quran icon image is missing or invalid');
  }
  const imageStats = await sharp(imagePath).stats();
  if (imageStats.channels.slice(0, 3).every(channel => channel.stdev < 2)) {
    throw new Error('The realistic Quran icon image appears blank');
  }
  const root = path.join(__dirname, '../android/app/src/main/res');

  // Generate Android, PWA, Apple and desktop icons from the user-provided Quran image in public/icon.jpg.
  const publicDir = path.join(__dirname, '../public');
  await sharp(imagePath).resize(192, 192).png().toFile(path.join(publicDir, 'pwa-192x192.png'));
  await sharp(imagePath).resize(512, 512).png().toFile(path.join(publicDir, 'pwa-512x512.png'));
  await sharp(imagePath).resize(512, 512).png().toFile(path.join(publicDir, 'pwa-maskable-512x512.png'));
  await sharp(imagePath).resize(180, 180).png().toFile(path.join(publicDir, 'apple-touch-icon.png'));
  await sharp(imagePath).resize(64, 64).png().toFile(path.join(publicDir, 'favicon.png'));


  // Legacy launcher icons for Android versions below Android 8.
  const sizes = {
    'mipmap-mdpi': 48,
    'mipmap-hdpi': 72,
    'mipmap-xhdpi': 96,
    'mipmap-xxhdpi': 144,
    'mipmap-xxxhdpi': 192
  };

  for (const [folder, size] of Object.entries(sizes)) {
    const dir = path.join(root, folder);
    fs.mkdirSync(dir, { recursive: true });
    for (const name of ['ic_launcher.png', 'ic_launcher_round.png']) {
      await sharp(imagePath).resize(size, size).png().toFile(path.join(dir, name));
    }
  }

  // Adaptive icons must reference a real drawable foreground. Pointing the
  // foreground back to @mipmap/ic_launcher creates a resource self-reference.
  const drawable = path.join(root, 'drawable-nodpi');
  fs.mkdirSync(drawable, { recursive: true });
  await sharp(imagePath).resize(432, 432).png()
    .toFile(path.join(drawable, 'quran_launcher_foreground.png'));

  const adaptiveDir = path.join(root, 'mipmap-anydpi-v26');
  fs.mkdirSync(adaptiveDir, { recursive: true });
  const adaptiveXml =
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">' +
    '<background android:drawable="@color/ic_launcher_background"/>' +
    '<foreground android:drawable="@drawable/quran_launcher_foreground"/>' +
    '</adaptive-icon>';

  fs.writeFileSync(path.join(adaptiveDir, 'ic_launcher.xml'), adaptiveXml);
  fs.writeFileSync(path.join(adaptiveDir, 'ic_launcher_round.xml'), adaptiveXml);

  const values = path.join(root, 'values');
  fs.mkdirSync(values, { recursive: true });
  fs.writeFileSync(
    path.join(values, 'ic_launcher_background.xml'),
    '<resources><color name="ic_launcher_background">#043D30</color></resources>'
  );

  const strings = path.join(values, 'strings.xml');
  let stringsXml = fs.existsSync(strings)
    ? fs.readFileSync(strings, 'utf8')
    : '<resources></resources>';

  if (/<string name="app_name">[\s\S]*?<\/string>/.test(stringsXml)) {
    stringsXml = stringsXml.replace(
      /<string name="app_name">[\s\S]*?<\/string>/,
      '<string name="app_name">Bangla Mushaf Prayer</string>'
    );
  } else {
    stringsXml = stringsXml.replace(
      '</resources>',
      '<string name="app_name">Bangla Mushaf Prayer</string></resources>'
    );
  }
  fs.writeFileSync(strings, stringsXml);

  // Explicitly bind the generated launcher resources in the Android manifest.
  // Capacitor creates this manifest during "cap add android".
  const manifest = path.join(root, '..', 'AndroidManifest.xml');
  if (!fs.existsSync(manifest)) {
    throw new Error('AndroidManifest.xml was not generated by Capacitor');
  }
  let manifestXml = fs.readFileSync(manifest, 'utf8');
  // Explicit permissions for GPS, Android 13+ notifications and exact alarms.
  const requiredPermissions = [
    'android.permission.ACCESS_COARSE_LOCATION',
    'android.permission.ACCESS_FINE_LOCATION',
    'android.permission.POST_NOTIFICATIONS',
    'android.permission.SCHEDULE_EXACT_ALARM',
    'android.permission.RECEIVE_BOOT_COMPLETED'
  ];
  for (const permission of requiredPermissions) {
    if (!manifestXml.includes('android:name="' + permission + '"')) {
      manifestXml = manifestXml.replace('</manifest>', '<uses-permission android:name="' + permission + '"/></manifest>');
    }
  }
  if (/<application\b[^>]*>/s.test(manifestXml)) {
    manifestXml = manifestXml.replace(/<application\b([^>]*)>/s, (match, attrs) => {
      let next = attrs
        .replace(/\s+android:icon="[^"]*"/g, '')
        .replace(/\s+android:roundIcon="[^"]*"/g, '');
      next += ' android:icon="@mipmap/ic_launcher" android:roundIcon="@mipmap/ic_launcher_round"';
      return '<application' + next + '>';
    });
  } else {
    throw new Error('Android application tag not found in manifest');
  }
  fs.writeFileSync(manifest, manifestXml);
})().catch(error => {
  console.error(error);
  process.exit(1);
});
